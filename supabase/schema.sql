-- SpiroBuddy tables for Supabase (Postgres). Same tables as the local SQLite demo store.
-- Paste this whole file into Supabase > SQL Editor > New query > Run. Safe to run twice.
-- Row Level Security is ON with no public policies: only the server's service-role /
-- secret key (which bypasses RLS) can read or write. The browser never talks to Supabase.

create table if not exists public.patients (
  id               bigint generated by default as identity primary key,
  name             text not null,
  age              int,
  sex              text,
  surgery          text,
  surgery_date     date,
  language         text not null default 'en' check (language in ('en','hi','ta')),
  target_ml        int  not null default 2000,
  hold_target_s    real not null default 3,
  family_phone     text,
  nurse_phone      text,
  personal_best_ml real not null default 0,
  created_at       timestamptz not null default now()
);

create table if not exists public.sessions (
  id            bigint generated by default as identity primary key,
  patient_id    bigint not null references public.patients(id) on delete cascade,
  started_at    timestamptz not null default now(),
  slot_date     date not null,
  slot_hour     int  not null,
  breaths_count int  not null default 0,
  best_ml       real not null default 0,
  avg_score     real not null default 0,
  source        text not null default 'demo' check (source in ('demo','device','app'))
);

create table if not exists public.breaths (
  id         bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  patient_id bigint not null,
  t          bigint,
  features   jsonb not null,
  label      text check (label in ('good','too_fast','too_shallow','no_hold')),
  score      real
);

create table if not exists public.slots (
  patient_id bigint not null references public.patients(id) on delete cascade,
  slot_date  date   not null,
  slot_hour  int    not null,
  status     text   not null check (status in ('done','missed')),
  session_id bigint references public.sessions(id) on delete set null,
  primary key (patient_id, slot_date, slot_hour)
);

create table if not exists public.messages (
  id         bigint generated by default as identity primary key,
  patient_id bigint references public.patients(id) on delete set null,
  kind       text,
  to_role    text,
  to_number  text,
  text       text,
  sent       boolean not null default false,
  dry_run    boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.breaths_labelled (
  id         bigint generated by default as identity primary key,
  person     text,
  label      text check (label in ('good','too_fast','too_shallow','no_hold')),
  samples    jsonb,
  features   jsonb,
  created_at timestamptz not null default now()
);

-- Indexes for the dashboard queries
create index if not exists sessions_patient_date_idx on public.sessions (patient_id, slot_date);
create index if not exists sessions_slot_date_idx    on public.sessions (slot_date);
create index if not exists breaths_session_idx       on public.breaths (session_id);
create index if not exists breaths_patient_idx       on public.breaths (patient_id);
create index if not exists slots_slot_date_idx       on public.slots (slot_date);
create index if not exists messages_patient_idx      on public.messages (patient_id);
create index if not exists messages_created_idx      on public.messages (created_at desc);

-- Row Level Security on, no policies => anon/authenticated keys get nothing.
alter table public.patients         enable row level security;
alter table public.sessions         enable row level security;
alter table public.breaths          enable row level security;
alter table public.slots            enable row level security;
alter table public.messages         enable row level security;
alter table public.breaths_labelled enable row level security;

-- ============================================================================ comms
-- Escalation ladder, calls, alerts, guardians (care circle), cheers, inbound replies.
-- Owned by backend/app/comms/ – see docs/COMMS.md and ARCHITECTURE.md CONTRACT D2.

create table if not exists public.guardians (
  id          bigint generated by default as identity primary key,
  patient_id  bigint not null references public.patients(id) on delete cascade,
  name        text not null,
  relation    text,
  phone       text,
  language    text not null default 'hi',
  channel     text not null default 'both' check (channel in ('whatsapp','call','sms','both')),
  city        text,
  quiet_start text,              -- 'HH:MM' IST, null = use the patient's quiet hours
  quiet_end   text,
  is_primary  boolean not null default false,
  consent     boolean not null default false,  -- recorded consent for automated calls/messages (TRAI)
  consent_at  timestamptz,                     -- when it was recorded (TRAI: consent has a validity period)
  token       text unique,       -- magic link: /guardian.html?t=<token>
  created_at  timestamptz not null default now()
);

create table if not exists public.care_settings (
  patient_id bigint primary key references public.patients(id) on delete cascade,
  config     jsonb not null default '{}'::jsonb,   -- patient_phone, quiet hours, ladder steps
  updated_at timestamptz not null default now()
);

create table if not exists public.alerts (
  id           bigint generated by default as identity primary key,
  patient_id   bigint references public.patients(id) on delete cascade,
  kind         text,     -- missed | red_flag | no_answer | low_trend | callback
  severity     text check (severity in ('red','amber','info')),
  title        text,
  detail       text,
  status       text not null default 'open' check (status in ('open','acknowledged','snoozed','resolved')),
  assigned_to  text,
  snooze_until timestamptz,
  run_id       bigint,
  acted_by     text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.escalations (
  id          bigint generated by default as identity primary key,
  patient_id  bigint references public.patients(id) on delete cascade,
  reason      text,      -- missed | manual | demo | red_flag
  status      text,      -- active | resolved | completed | stopped
  speed       text,      -- real | fast
  step_index  int not null default 0,
  next_at     timestamptz,
  slot_date   date,
  slot_hour   int,
  snoozes     int not null default 0,
  outcome     text,
  meta        jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.escalation_events (
  id         bigint generated by default as identity primary key,
  patient_id bigint references public.patients(id) on delete cascade,
  run_id     bigint,
  kind       text,
  channel    text,
  actor      text,
  to_name    text,
  title      text,
  detail     text,
  status     text,
  ref_id     bigint,
  created_at timestamptz not null default now()
);

create table if not exists public.calls (
  id           bigint generated by default as identity primary key,
  patient_id   bigint references public.patients(id) on delete cascade,
  run_id       bigint,
  guardian_id  bigint,
  to_role      text,
  to_name      text,
  to_number    text,
  purpose      text,     -- reminder | checkin (AI conversation) | guardian | guardian_red_flag | nurse_bridge
  provider     text,     -- twilio | exotel | sarvam_agent | dry_run (provider_sid = Sarvam attempt_id)
  provider_sid text,
  status       text,
  digits       text,
  outcome      text,
  language     text,
  script       text,
  meta         jsonb,
  ring_until   timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.cheers (
  id          bigint generated by default as identity primary key,
  patient_id  bigint references public.patients(id) on delete cascade,
  guardian_id bigint,
  from_name   text,
  text        text,
  language    text,
  status      text not null default 'queued' check (status in ('queued','played')),
  created_at  timestamptz not null default now(),
  played_at   timestamptz
);

create table if not exists public.inbound_messages (
  id          bigint generated by default as identity primary key,
  patient_id  bigint references public.patients(id) on delete cascade,
  guardian_id bigint,
  from_number text,
  from_role   text,
  from_name   text,
  channel     text,
  body        text,
  intent      text,
  reply       text,
  created_at  timestamptz not null default now()
);

create index if not exists alerts_status_idx   on public.alerts (status, patient_id);
create index if not exists events_patient_idx  on public.escalation_events (patient_id, created_at desc);
create index if not exists calls_status_idx    on public.calls (status);
create index if not exists calls_sid_idx       on public.calls (provider_sid);   -- Sarvam webhook lookup
create index if not exists esc_status_idx      on public.escalations (status);

alter table public.guardians         enable row level security;
alter table public.care_settings     enable row level security;
alter table public.alerts            enable row level security;
alter table public.escalations       enable row level security;
alter table public.escalation_events enable row level security;
alter table public.calls             enable row level security;
alter table public.cheers            enable row level security;
alter table public.inbound_messages  enable row level security;
