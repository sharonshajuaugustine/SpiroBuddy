-- SpiroBuddy tables for Supabase (Postgres). Same tables as the local SQLite demo store.
-- Paste this whole file into Supabase > SQL Editor > New query > Run. Safe to run twice.
-- Row Level Security is ON with no public policies: only the server's service-role /
-- secret key (which bypasses RLS) can read or write. The browser never talks to Supabase.

create table if not exists public.patients (
  id               bigint generated by default as identity primary key,
  name             text not null,
  age              int,
  sex              text,
  surgery          text,
  surgery_date     date,
  language         text not null default 'en' check (language in ('en','hi','ta')),
  target_ml        int  not null default 2000,
  hold_target_s    real not null default 3,
  family_phone     text,
  nurse_phone      text,
  personal_best_ml real not null default 0,
  created_at       timestamptz not null default now()
);

create table if not exists public.sessions (
  id            bigint generated by default as identity primary key,
  patient_id    bigint not null references public.patients(id) on delete cascade,
  started_at    timestamptz not null default now(),
  slot_date     date not null,
  slot_hour     int  not null,
  breaths_count int  not null default 0,
  best_ml       real not null default 0,
  avg_score     real not null default 0,
  source        text not null default 'demo' check (source in ('demo','device','app'))
);

create table if not exists public.breaths (
  id         bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  patient_id bigint not null,
  t          bigint,
  features   jsonb not null,
  label      text check (label in ('good','too_fast','too_shallow','no_hold')),
  score      real
);

create table if not exists public.slots (
  patient_id bigint not null references public.patients(id) on delete cascade,
  slot_date  date   not null,
  slot_hour  int    not null,
  status     text   not null check (status in ('done','missed')),
  session_id bigint references public.sessions(id) on delete set null,
  primary key (patient_id, slot_date, slot_hour)
);

create table if not exists public.messages (
  id         bigint generated by default as identity primary key,
  patient_id bigint references public.patients(id) on delete set null,
  kind       text,
  to_role    text,
  to_number  text,
  text       text,
  sent       boolean not null default false,
  dry_run    boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.breaths_labelled (
  id         bigint generated by default as identity primary key,
  person     text,
  label      text check (label in ('good','too_fast','too_shallow','no_hold')),
  samples    jsonb,
  features   jsonb,
  created_at timestamptz not null default now()
);

-- Indexes for the dashboard queries
create index if not exists sessions_patient_date_idx on public.sessions (patient_id, slot_date);
create index if not exists sessions_slot_date_idx    on public.sessions (slot_date);
create index if not exists breaths_session_idx       on public.breaths (session_id);
create index if not exists breaths_patient_idx       on public.breaths (patient_id);
create index if not exists slots_slot_date_idx       on public.slots (slot_date);
create index if not exists messages_patient_idx      on public.messages (patient_id);
create index if not exists messages_created_idx      on public.messages (created_at desc);

-- Row Level Security on, no policies => anon/authenticated keys get nothing.
alter table public.patients         enable row level security;
alter table public.sessions         enable row level security;
alter table public.breaths          enable row level security;
alter table public.slots            enable row level security;
alter table public.messages         enable row level security;
alter table public.breaths_labelled enable row level security;
