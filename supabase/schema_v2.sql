alter table public.patients add column if not exists hospital_id       bigint references public.hospitals(id) on delete set null;
alter table public.patients add column if not exists primary_doctor_id bigint references public.staff(id) on delete set null;
alter table public.patients add column if not exists ward              text;
alter table public.patients add column if not exists bed               text;
alter table public.patients add column if not exists mrn               text;
alter table public.patients add column if not exists phone             text;
alter table public.patients add column if not exists city              text;
alter table public.patients add column if not exists emergency_contact jsonb;
alter table public.patients add column if not exists allergies_text    text;   -- "as recorded by doctor"
alter table public.patients add column if not exists discharge_date    date;
alter table public.patients add column if not exists programme_status  text not null default 'active';  -- active | paused | completed | stopped | deceased
alter table public.patients add column if not exists routine           jsonb;  -- {wake, breakfast, lunch, dinner, bed}
alter table public.patients add column if not exists app_token_hash    text;   -- sha256 of the patient app token
alter table public.patients add column if not exists app_token_hint    text;

-- New patients get ids from 1000 up (the seed uses fixed small ids).
select setval(pg_get_serial_sequence('public.patients','id'),
              greatest(1000, coalesce((select max(id) from public.patients),0)+1), false);

-- ============================================================================ care team and consent

create table if not exists public.care_team (
  id          bigint generated by default as identity (start with 1000) primary key,
  hospital_id bigint references public.hospitals(id) on delete cascade,
  patient_id  bigint not null references public.patients(id) on delete cascade,
  staff_id    bigint not null references public.staff(id) on delete cascade,
  role        text,                     -- primary | consulting | nurse
  created_at  timestamptz not null default now()
);

create table if not exists public.consents (
  id            bigint generated by default as identity (start with 1000) primary key,
  hospital_id   bigint references public.hospitals(id) on delete cascade,
  patient_id    bigint not null references public.patients(id) on delete cascade,
  version       int not null default 1,
  items         jsonb not null default '{}'::jsonb,   -- {care_reminders, family_sharing, ...}
  method        text,                   -- self | witness_thumbprint | guardian
  taken_by      bigint,                 -- staff id
  language      text,
  read_aloud    boolean not null default false,
  teach_back_ok boolean,
  created_at    timestamptz not null default now(),
  withdrawn_at  timestamptz
