-- SpiroBuddy 2.0 tables for Supabase (Postgres): hospitals, staff logins, nurse keys,
-- prescriptions and doses, appointments, documents, audit and AI registers, devices.
-- Paste this whole file into Supabase > SQL Editor > New query > Run, AFTER schema.sql.
-- Safe to run twice. Additive only: it never drops or renames a table or a column.
-- Row Level Security is ON with no public policies: only the server's service-role /
-- secret key (which bypasses RLS) can read or write. The browser never talks to Supabase.
-- Same tables and columns as the local SQLite store (backend/app/store.py, SQLITE_DDL_V2).
-- New ids start at 1000, so the demo seed's fixed small ids never collide with new rows.
-- Times are timestamptz (the server always writes ISO 8601 with the IST offset).

-- ============================================================================ hospitals and staff

create table if not exists public.hospitals (
  id                     bigint generated by default as identity (start with 1000) primary key,
  name                   text not null,
  city                   text,
  address                text,
  phone                  text,
  timezone               text not null default 'Asia/Kolkata',
  languages              jsonb not null default '[]'::jsonb,
  departments            jsonb not null default '[]'::jsonb,
  wards                  jsonb not null default '[]'::jsonb,
  join_code_hash         text,            -- sha256 of the join code, never the code itself
  join_code_hint         text,            -- e.g. the last 2 characters, for the admin page
  join_requires_approval boolean not null default true,
  settings               jsonb not null default '{}'::jsonb,   -- spec §8.3 settings object
  created_at             timestamptz not null default now()
);

create table if not exists public.staff (
  id             bigint generated by default as identity (start with 1000) primary key,
  hospital_id    bigint references public.hospitals(id) on delete cascade,
  role           text not null check (role in ('admin','doctor','nurse')),
  name           text not null,
  email          text not null,         -- stored lower-case; unique (see the index below)
  password_hash  text,                  -- argon2
  phone          text,
  department     text,
  specialty      text,
  reg_no_display text,
  status         text not null default 'active' check (status in ('pending','active','disabled')),
  failed_logins  int not null default 0,
  locked_until   timestamptz,
  last_login_at  timestamptz,
  created_at     timestamptz not null default now()
);

create table if not exists public.auth_sessions (
  id           bigint generated by default as identity (start with 1000) primary key,
  hospital_id  bigint references public.hospitals(id) on delete cascade,
  kind         text not null default 'staff' check (kind in ('staff','patient')),
  staff_id     bigint references public.staff(id) on delete cascade,
  patient_id   bigint,                  -- patient sessions; no FK so they survive a demo reset (same ids)
  token_hash   text not null unique,    -- sha256 of the cookie token
  expires_at   timestamptz not null,
  ip           text,
  user_agent   text,
  revoked_at   timestamptz,
  last_seen_at timestamptz,
  created_at   timestamptz not null default now()
);

create table if not exists public.access_keys (
  id          bigint generated by default as identity (start with 1000) primary key,
  hospital_id bigint references public.hospitals(id) on delete cascade,
  created_by  bigint references public.staff(id) on delete cascade,   -- the doctor
  label       text,
  key_hash    text not null unique,     -- sha256 of the nurse key, never the key itself
  key_hint    text,
  scope       text not null default 'patients' check (scope in ('all','patients')),
  patient_ids jsonb not null default '[]'::jsonb,
  permissions jsonb not null default '[]'::jsonb,
  expires_at  timestamptz,
  max_uses    int default 1,            -- null = no limit
  uses        int not null default 0,
  revoked_at  timestamptz,
  created_at  timestamptz not null default now()
);

create table if not exists public.key_grants (
  id          bigint generated by default as identity (start with 1000) primary key,
  hospital_id bigint references public.hospitals(id) on delete cascade,
  key_id      bigint not null references public.access_keys(id) on delete cascade,
  staff_id    bigint not null references public.staff(id) on delete cascade,
  granted_at  timestamptz not null default now(),
  created_at  timestamptz not null default now()
);

