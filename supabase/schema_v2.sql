-- ============================================================================ documents, prescriptions, doses

create table if not exists public.documents (
  id                 bigint generated by default as identity (start with 1000) primary key,
  hospital_id        bigint references public.hospitals(id) on delete cascade,
  patient_id         bigint not null references public.patients(id) on delete cascade,
  kind               text not null default 'other',   -- prescription | discharge_summary | lab_report | scan_report | consent_form | other
  title              text,
  doc_date           date,
  source             text,
  storage_path       text not null,     -- random key in the private bucket / backend/data/uploads
  mime               text,
  size               bigint,
  sha256             text,
  thumb_path         text,
  uploaded_by_role   text,
  uploaded_by_id     bigint,
  visible_to_patient boolean not null default false,
  visible_to_family  boolean not null default false,
  ai_suggested       jsonb,             -- {kind, title, doc_date} only
  deleted_at         timestamptz,       -- soft delete
  created_at         timestamptz not null default now()
);

create table if not exists public.prescriptions (
  id                  bigint generated by default as identity (start with 1000) primary key,
  hospital_id         bigint references public.hospitals(id) on delete cascade,
  patient_id          bigint not null references public.patients(id) on delete cascade,
  source              text,             -- doctor_typed | doctor_upload | patient_upload
  document_id         bigint references public.documents(id) on delete set null,
  status              text not null default 'draft' check (status in ('draft','needs_review','approved','rejected','stopped','superseded')),
  version             int not null default 1,
  supersedes_id       bigint references public.prescriptions(id) on delete set null,
  prescriber_on_paper text,
  prescribed_on       date,
  ai_event_id         bigint,
  reviewed_by         bigint,
  reviewed_at         timestamptz,
  created_by          bigint,
  created_at          timestamptz not null default now()
);

create table if not exists public.prescription_items (
  id               bigint generated by default as identity (start with 1000) primary key,
  hospital_id      bigint references public.hospitals(id) on delete cascade,
  prescription_id  bigint not null references public.prescriptions(id) on delete cascade,
  patient_id       bigint references public.patients(id) on delete cascade,   -- copy of the prescription's, for scoping
  line_no          int,
  drug_name        text,                -- exactly as written, never translated
  form             text,
  strength         text,
  dose_qty         real,
  dose_unit        text,
  frequency_raw    text,
  frequency_code   text,
  times            jsonb,               -- ["08:00","20:00"] from the routine and the normaliser
  food_timing      text,
  duration_raw     text,
  duration_days    int,
  start_date       date,
  end_date         date,
  as_needed        boolean not null default false,
  instructions_raw text,
  confidence       real,
  unclear_fields   jsonb not null default '[]'::jsonb,
  box_2d           jsonb,
  status           text not null default 'pending' check (status in ('pending','confirmed','edited','removed')),
  confirmed_by     bigint,
  confirmed_at     timestamptz,
  created_at       timestamptz not null default now()
);

create table if not exists public.dose_events (
  id               bigint generated by default as identity (start with 1000) primary key,
  hospital_id      bigint references public.hospitals(id) on delete cascade,
  patient_id       bigint not null references public.patients(id) on delete cascade,
  item_id          bigint references public.prescription_items(id) on delete cascade,
  due_at           timestamptz not null,
  status           text not null default 'upcoming',   -- upcoming | due | reported_taken | missed | paused | cancelled
  reported_at      timestamptz,
  reported_by_role text,
  reported_by_id   bigint,
  channel          text,
  note             text,
  snooze_until     timestamptz,
  created_at       timestamptz not null default now()
);

-- ============================================================================ appointments

create table if not exists public.appointments (
  id                bigint generated by default as identity (start with 1000) primary key,
  hospital_id       bigint references public.hospitals(id) on delete cascade,
  patient_id        bigint not null references public.patients(id) on delete cascade,
  doctor_id         bigint references public.staff(id) on delete cascade,
  department        text,
  kind              text not null default 'follow_up',  -- follow_up | review | other
  start_at          timestamptz not null,
  end_at            timestamptz,
  status            text not null default 'requested' check (status in ('requested','confirmed','cancelled','attended','no_show','declined')),
  requested_by_role text,
  reason_text       text,
  location          text,
  notes             text,
  created_at        timestamptz not null default now()
);

create table if not exists public.availability (
  id           bigint generated by default as identity (start with 1000) primary key,
  hospital_id  bigint references public.hospitals(id) on delete cascade,
  doctor_id    bigint not null references public.staff(id) on delete cascade,
  weekday      int not null,            -- 0 = Monday ... 6 = Sunday
  start_time   text not null,           -- 'HH:MM' IST
  end_time     text not null,
  slot_minutes int not null default 15,
  location     text,
  valid_from   date,
  valid_to     date,
  created_at   timestamptz not null default now()
);

create table if not exists public.availability_exceptions (
  id          bigint generated by default as identity (start with 1000) primary key,
  hospital_id bigint references public.hospitals(id) on delete cascade,
  doctor_id   bigint not null references public.staff(id) on delete cascade,
  date        date not null,
  kind        text not null check (kind in ('leave','extra')),
  start_time  text,                     -- 'HH:MM'; empty = the whole day
  end_time    text,
  created_at  timestamptz not null default now()
);

-- ============================================================================ notes, audit, AI register

create table if not exists public.notes (
  id          bigint generated by default as identity (start with 1000) primary key,
  hospital_id bigint references public.hospitals(id) on delete cascade,
  patient_id  bigint not null references public.patients(id) on delete cascade,
  author_id   bigint,
  kind        text not null default 'note',   -- note | call | handover
  text        text not null,
  edited_at   timestamptz,
  created_at  timestamptz not null default now()
);

-- No foreign keys on the two registers: they are logs and must outlive a demo reset.
create table if not exists public.audit_events (
  id            bigint generated by default as identity (start with 1000) primary key,
  hospital_id   bigint,
  at            timestamptz not null default now(),
  actor_type    text,                   -- staff | patient | guardian | system
  actor_id      bigint,
  actor_role    text,
  action        text not null,          -- auth.login, patient.view, rx.approve, ...
  resource_type text,
  resource_id   text,
  patient_id    bigint,
  detail        jsonb,                  -- never a token, password or document content
  ip            text,
  request_id    text,
  prev_hash     text,
  hash          text,
  created_at    timestamptz not null default now()
);

create table if not exists public.ai_events (
  id             bigint generated by default as identity (start with 1000) primary key,
  hospital_id    bigint,
  purpose        text not null,         -- rx_extract | doc_suggest | summary
  provider       text,
  model          text,
  prompt_version text,
  input_ref      text,                  -- a reference (document id / hash), never the content
  output         jsonb,
  latency_ms     int,
  ok             boolean not null default false,
  error          text,
  patient_id     bigint,
  reviewed_by    bigint,
  reviewed_at    timestamptz,
  decision       text,
  lines_total    int,
  lines_edited   int,
  lines_removed  int,
  created_at     timestamptz not null default now()
);

