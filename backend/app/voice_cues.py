# Display order for the "Voice check" card and the clip generator.
CUE_ORDER = (["ready", "breathe_in", "slower", "hold", "count_3", "count_2", "count_1",
              "breathe_out", "great_breath", "too_fast", "breathe_deeper", "hold_longer"]
             + [f"breath_{n}" for n in range(1, 11)]
             + ["session_complete", "reminder", "missed_reminder", "red_flag",
                "encourage_1", "encourage_2", "encourage_3", "question_noted", "faq_how_often"])
assert set(CUE_ORDER) == set(CUES), "CUE_ORDER and CUES are out of sync"


def cue_text(cue: str, lang: str) -> str | None:
    """Text of a cue in a language (falls back to English); None if the cue doesn't exist."""
    row = CUES.get(cue)
    if not row:
        return None
    return row.get(lang) or row.get("en")


def all_cues() -> dict:
    """{order, languages, cues} – the shape of web/audio/cues.json and GET /api/voice/cues."""
    return {"order": CUE_ORDER, "languages": LANG_ORDER, "cues": CUES}
